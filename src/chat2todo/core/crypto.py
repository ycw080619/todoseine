INV = [0] * 256
for _i, _v in enumerate(SBOX):
    INV[_v] = _i
RCON = [0x01, 0x02, 0x04, 0x08, 0x10, 0x20, 0x40, 0x80, 0x1B, 0x36, 0x6C, 0xD8, 0xAB, 0x4D]


def _xt(a: int) -> int:
    return ((a << 1) ^ 0x1B) & 0xFF if a & 0x80 else (a << 1) & 0xFF


def _mul(a: int, b: int) -> int:
    r = 0
    while b:
        if b & 1:
            r ^= a
        a = _xt(a)
        b >>= 1
    return r


def _tables():
    return {x: [_mul(i, x) for i in range(256)] for x in (9, 11, 13, 14)}


MUL = _tables()


def _expand(key: bytes):
    nk = len(key) // 4
    nr = nk + 6
    w = [list(key[4 * i:4 * i + 4]) for i in range(nk)]
    for i in range(nk, 4 * (nr + 1)):
        t = list(w[i - 1])
        if i % nk == 0:
            t = t[1:] + t[:1]
            t = [SBOX[b] for b in t]
            t[0] ^= RCON[i // nk - 1]
        elif nk > 6 and i % nk == 4:
            t = [SBOX[b] for b in t]
        w.append([w[i - nk][j] ^ t[j] for j in range(4)])
    return [sum(w[4 * r:4 * r + 4], []) for r in range(nr + 1)], nr


def decrypt_block(key: bytes, block: bytes) -> bytes:
    """解密单个 16 字节块（AES-128/192/256 由 key 长度决定）。"""
    rk, nr = _expand(key)
    s = [block[i] ^ rk[nr][i] for i in range(16)]
    for r in range(nr - 1, -1, -1):
        s = [s[0], s[13], s[10], s[7], s[4], s[1], s[14], s[11],
             s[8], s[5], s[2], s[15], s[12], s[9], s[6], s[3]]
        s = [INV[b] for b in s]
        s = [s[i] ^ rk[r][i] for i in range(16)]
        if r:
            o = []
            for c in range(4):
                a = s[4 * c:4 * c + 4]
                o += [MUL[14][a[0]] ^ MUL[11][a[1]] ^ MUL[13][a[2]] ^ MUL[9][a[3]],
                      MUL[9][a[0]] ^ MUL[14][a[1]] ^ MUL[11][a[2]] ^ MUL[13][a[3]],
                      MUL[13][a[0]] ^ MUL[9][a[1]] ^ MUL[14][a[2]] ^ MUL[11][a[3]],
                      MUL[11][a[0]] ^ MUL[13][a[1]] ^ MUL[9][a[2]] ^ MUL[14][a[3]]]
            s = o
    return bytes(s)


def cbc_decrypt_first_block(key: bytes, iv: bytes, ciphertext: bytes) -> bytes:
    return bytes(a ^ b for a, b in zip(decrypt_block(key, ciphertext[:16]), iv[:16]))


def derive_key(passphrase: bytes, salt: bytes, iterations: int = 4000,
               digest: str = "sha512", length: int = 32) -> bytes:
    """QQ 数据库的派生参数：PBKDF2-HMAC-SHA512 / 4000 次。

    注意：这不是 SQLCipher 4 的默认值（256000），QQ 用的是 4000。
    校验函数 verify_sqlcipher_key 不传 iterations 时走这个默认值。
    """
    return hashlib.pbkdf2_hmac(digest, passphrase, salt, iterations, length)


SQLITE_MAGIC = b"SQLite format 3\x00"


def verify_sqlcipher_key(passphrase: str, db_path: str, iterations: int = 4000,
                         digest: str = "sha512", header_size: int = 1024) -> bool:
    """校验一个口令能否解开该库的第一页。

    布局：1024 字节自定义头之后是标准 SQLCipher 库，
    前 16 字节为 salt，紧接 16 字节 IV，再往后是密文。
    """
    with open(db_path, "rb") as fh:
        fh.seek(header_size)
        salt = fh.read(16)
        iv = fh.read(16)
        ct = fh.read(64)
    if len(salt) < 16 or len(iv) < 16 or len(ct) < 16:
        return False
    key = derive_key(passphrase.encode("utf-8"), salt, iterations, digest)
    return cbc_decrypt_first_block(key, iv, ct) == SQLITE_MAGIC
